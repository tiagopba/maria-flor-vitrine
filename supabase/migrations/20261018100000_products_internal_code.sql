-- PREPARADA, NÃO APLICADA — aguardando aprovação explícita do usuário.
--
-- Identificador interno automático e sequencial para produtos
-- (products.internal_code), substituindo o código manual digitado pela
-- admin SÓ PARA PRODUTO NOVO daqui pra frente. Nada aditivo aqui toca em
-- `products.code` de uma linha já existente — nenhum UPDATE em massa, nenhum
-- backfill dessa coluna. `code` legado continua byte a byte igual pros 579
-- produtos de hoje, e continua sendo a coluna que Meta Catalog, Pixel/CAPI,
-- WhatsApp, JSON-LD, slugs, busca pública e seleção compartilhada já leem —
-- zero mudança de contrato pra esses sistemas.
--
-- Auditoria prévia (somente leitura, feita antes de escrever este arquivo):
--   - 579 produtos (325 arquivados / 254 não arquivados);
--   - created_at entre 2026-08-28 e 2026-10-15;
--   - 8 produtos já têm `code` puramente numérico de 8 dígitos, todos entre
--     10.000.011 e 50.001.156 — nenhuma colisão possível com a faixa de
--     internal_code (que começa em 1 e levaria décadas pra chegar nessa
--     ordem de grandeza), e tecnicamente nenhuma colisão é possível de
--     qualquer forma: são colunas diferentes, cada uma com sua própria
--     unique constraint;
--   - nenhuma coluna/sequence chamada internal_code existe hoje (checado em
--     information_schema.columns e pg_sequences, não só nas migrations).

-- 1) coluna nova, ainda sem identity — precisa ficar "solta" durante o
--    backfill porque uma coluna GENERATED ALWAYS AS IDENTITY rejeita
--    qualquer valor explícito até em UPDATE, não só em INSERT.
alter table products add column internal_code bigint;

-- 2) backfill determinístico por created_at ASC, id ASC (id como tie-break
--    de empate exato de timestamp) — numeração 1..N calculada inteiramente
--    dentro do Postgres (row_number()), nunca um MAX()+1 calculado fora do
--    banco. Inclui produtos arquivados de propósito: eles fazem parte da
--    sequência histórica tanto quanto os ativos (nenhum filtro de status
--    aqui).
with ordered as (
  select id, row_number() over (order by created_at asc, id asc) as rn
  from products
)
update products p
set internal_code = ordered.rn
from ordered
where ordered.id = p.id;

-- 3) trava o formato antes de virar identity: toda linha já tem um valor
--    numérico e único nesta altura (passo 2 é uma bijeção 1..N sobre as
--    linhas existentes).
alter table products alter column internal_code set not null;
alter table products add constraint products_internal_code_key unique (internal_code);

-- 4) só agora liga a identity real do Postgres — gerada automaticamente em
--    todo INSERT futuro que não informar o valor, nunca calculada no
--    frontend/RPC. START WITH é calculado dinamicamente no momento da
--    aplicação (nunca um literal fixo escrito hoje): continua exatamente
--    depois do maior valor que o backfill acabou de atribuir, então o
--    próximo produto cadastrado recebe o número seguinte, sem pular nem
--    repetir. GENERATED BY DEFAULT (não ALWAYS) deixa a função de
--    auto-preenchimento de `code` no passo 6 inserir sem precisar informar
--    internal_code explicitamente — é o comportamento padrão de qualquer
--    insert novo.
do $$
declare
  v_next bigint;
begin
  select coalesce(max(internal_code), 0) + 1 into v_next from products;
  execute format(
    'alter table products alter column internal_code add generated by default as identity (start with %s)',
    v_next
  );
end
$$;

-- 5) imutabilidade: nenhum UPDATE pode mudar internal_code depois do
--    INSERT, nem por engano de um código futuro, nem por um comando manual
--    no SQL Editor. Erro claro e alto (sem errcode especial — não é um caso
--    pra a aplicação capturar e traduzir; se isso disparar, é um bug real
--    que precisa quebrar visivelmente).
create or replace function prevent_internal_code_update()
returns trigger
language plpgsql
as $$
begin
  if new.internal_code is distinct from old.internal_code then
    raise exception 'internal_code is immutable and cannot be changed after insert (id=%, old=%, new=%)',
      old.id, old.internal_code, new.internal_code;
  end if;
  return new;
end;
$$;

create trigger products_internal_code_immutable
  before update on products
  for each row execute function prevent_internal_code_update();

-- 6) preenchimento automático de `code` SÓ para produto novo: dispara em
--    INSERT, nunca em UPDATE — um produto já existente nunca passa por
--    aqui de novo. Só age quando o client não mandou `code` (a RPC
--    save_product_with_variants, a partir da migration seguinte, para de
--    enviar `code` na criação); se algum outro caminho ainda inserir com
--    `code` explícito, essa função respeita o valor dado e não o
--    sobrescreve. `new.internal_code` já está resolvido aqui dentro porque
--    o DEFAULT da coluna (passo 4) é aplicado à linha ANTES de qualquer
--    trigger BEFORE INSERT rodar — garantia do próprio Postgres, não uma
--    suposição.
create or replace function set_product_code_from_internal_code()
returns trigger
language plpgsql
as $$
begin
  if new.code is null then
    new.code := lpad(new.internal_code::text, 8, '0');
  end if;
  return new;
end;
$$;

create trigger products_default_code_from_internal_code
  before insert on products
  for each row execute function set_product_code_from_internal_code();

comment on column products.internal_code is
  'Identificador interno automático, sequencial e imutável (sequence real do Postgres via GENERATED BY DEFAULT AS IDENTITY). Nunca calculado no frontend/RPC, nunca reutilizado, nunca editável. Independente de products.code (legado, preservado para produtos existentes).';
